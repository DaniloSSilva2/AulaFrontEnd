//Criando vetor
const listaNomes = ['Marta', 'José', 'Maria']

console.log('\nExibindo todos os elementos.')
console.log(listaNomes)

console.log('\nExibindo o primeiro elemento.')
console.log(listaNomes[0])

console.log('\nAdicionando um elemento no vetor.')
listaNomes.push('Marilia')
console.log(listaNomes)

console.log('\nRemovendo um elemento específico.')
listaNomes.splice(1,1)
console.log(listaNomes)

console.log('\nRemovendo apenas o primeiro elemento.')
listaNomes.shift()
console.log(listaNomes)


console.log('\nRemovendo apenas o último elemento.')
listaNomes.pop()
console.log(listaNomes)











