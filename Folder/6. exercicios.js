//Faça uma arrow function que recebe um valor inteiro e verifica se o valor é positivo ou negativo(javascript)
const verificarSinal = (numero) => 
    numero > 0 ? 'Positivo' : numero < 0 ? 'Negativo' : 'Zero';

console.log(verificarSinal(7));    
console.log(verificarSinal(-3));   
console.log(verificarSinal(0));    




